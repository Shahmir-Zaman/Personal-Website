/*
New Meshy AI Avatar — loaded from avatar-new.glb

Scaffold generated by gltfjsx. Behavioral layer (head tracking, animation
state machine, interaction handlers) carried over from the previous avatar.

Node structure (from gltfjsx):
  Armature  rotation={[PI/2, 0, 0]}
    primitive  nodes.mixamorigHips
    skinnedMesh  Mesh_0  material=Avatar_Material

Animations baked into the GLB:
  Idle   339 frames   (Breathing Idle from Mixamo)
  Wave    69 frames   (Waving Gesture)
  Sad    106 frames   (Sad Idle)
  Run     22 frames   (not used yet)
  Angry   99 frames   (not used yet)
  Hang    39 frames   (not used yet)
*/

import React, { useState, useEffect } from 'react'
import { useGraph, useFrame } from '@react-three/fiber'
import { useGLTF, useAnimations } from '@react-three/drei'
import { SkeletonUtils } from 'three-stdlib'
import * as THREE from 'three'

// -- HEAD TRACKING CONFIG -- //
// How far the head can rotate to follow the cursor (radians) and how quickly it
// eases toward the target.
const MAX_YAW = 0.8     // left/right (~46°)
const MAX_PITCH = 0.45  // up/down (~26°)
const LOOK_LAMBDA = 10  // snappy and responsive follow
// If the head turns the wrong way, flip the matching sign to -1.
const YAW_DIR = 1       // left/right direction
const PITCH_DIR = 1     // up/down direction

// Reusable scratch objects so we don't allocate every frame.
const _euler = new THREE.Euler()
const _quat = new THREE.Quaternion()
const _inverse = new THREE.Quaternion()
const _headPos = new THREE.Vector3()
const _rayV = new THREE.Vector3()
const _rayDir = new THREE.Vector3()
const _targetWorld = new THREE.Vector3()
const _targetLocal = new THREE.Vector3()
const _cornerWorld = new THREE.Vector3()

// -- CLIP MAPPING -- //
// The new avatar's clips are named to match the state machine directly.
// No stub-avoidance remapping is needed (all clips are real motion).
const CLIP_FOR_STATE = {
  'Idle': 'Idle',
  'Sad Idle': 'Sad',
  'Wave': 'Wave',
  'Angry': 'Angry',
  'Run': 'Run',
}

// A clip is only usable if it has enough keyframes to be real motion rather
// than a two-key stub. Guards against export mistakes.
const isUsableClip = (action) => action && action.getClip().tracks.some((t) => t.times.length > 2)

export function Avatar({
  isHero,
  isWidget,
  isChatOpen,
  forcedAnimation,
  angryPulse,
  isChasing,
  chasePhase = 'IDLE',
  mouseTarget,
  widgetOrigin,
  onScreenPosUpdate,
  onChaseComplete,
  interactionPulse: externalInteractionPulse,
  onClick,
  onContextMenu,
  ...props
}) {
  const group = React.useRef()
  const avatarWorldPos = React.useRef(new THREE.Vector3())
  const avatarYaw = React.useRef(0)
  const avatarPitch = React.useRef(0)
  const avatarRoll = React.useRef(0)
  const avatarScale = React.useRef(1)
  const wasChasingRef = React.useRef(false)
  const { scene, animations } = useGLTF('/models/avatar-new.glb')

  // Defense-in-depth: Ensure the Run animation is strictly in-place (no forward root motion)
  // and all animation tracks start cleanly at t = 0 to prevent loop boundary clamping stalls
  React.useEffect(() => {
    if (!animations) return
    const runClip = animations.find((a) => a.name === 'Run' || a.name === 'run')
    if (runClip) {
      runClip.tracks.forEach((track) => {
        if (/hips/i.test(track.name) && track.name.endsWith('.position')) {
          const y0 = track.values[1] ?? 0
          for (let i = 1; i < track.values.length; i += 3) {
            track.values[i] = y0
          }
        }
      })
    }

    animations.forEach((clip) => {
      clip.tracks.forEach((track) => {
        if (track.times && track.times[0] > 0.001) {
          const newTimes = new Float32Array(track.times.length + 1)
          newTimes[0] = 0
          newTimes.set(track.times, 1)

          const stride = track.getValueSize ? track.getValueSize() : 4
          const newValues = new (track.values.constructor)(track.values.length + stride)
          newValues.set(track.values.subarray(0, stride), 0)
          newValues.set(track.values, stride)

          track.times = newTimes
          track.values = newValues
        }
      })
    })
  }, [animations])

  const clone = React.useMemo(() => SkeletonUtils.clone(scene), [scene])
  const { nodes, materials } = useGraph(clone)
  const { actions, mixer } = useAnimations(animations, group)

  // -- HEAD TRACKING (look toward the cursor) -- //
  const headBone = React.useMemo(() => (
    clone.getObjectByName('mixamorig:Head') ||
    clone.getObjectByName('mixamorigHead') ||
    clone.getObjectByName('Head') ||
    (() => {
      let found = null
      clone.traverse((child) => {
        if (!found && child.isBone && /head/i.test(child.name) && !/top|end/i.test(child.name)) {
          found = child
        }
      })
      return found
    })()
  ), [clone])

  const neckBone = React.useMemo(() => (
    clone.getObjectByName('mixamorig:Neck') ||
    clone.getObjectByName('mixamorigNeck') ||
    clone.getObjectByName('Neck') ||
    (() => {
      let found = null
      clone.traverse((child) => {
        if (!found && child.isBone && /neck/i.test(child.name)) {
          found = child
        }
      })
      return found
    })()
  ), [clone])

  const look = React.useRef({ yaw: 0, pitch: 0 })
  const globalPointer = React.useRef({ x: typeof window !== 'undefined' ? window.innerWidth / 2 : 0, y: typeof window !== 'undefined' ? window.innerHeight / 2 : 0 })

  useEffect(() => {
    const handleMove = (e) => {
      globalPointer.current.x = e.clientX
      globalPointer.current.y = e.clientY
    }
    window.addEventListener('pointermove', handleMove)
    return () => window.removeEventListener('pointermove', handleMove)
  }, [])

  // Touch screens have no hovering cursor to follow, so the head rests facing forward.
  const hasCursor = React.useRef(true)
  useEffect(() => {
    const query = window.matchMedia('(hover: hover) and (pointer: fine)')
    const update = () => { hasCursor.current = query.matches }
    update()
    query.addEventListener('change', update)
    return () => query.removeEventListener('change', update)
  }, [])

  // Runs at default priority, which registers AFTER drei's animation mixer, so
  // this offset is applied on top of whatever animation pose is playing.
  useFrame((state, delta) => {
    // 1. Fullscreen Desktop Goose Chase Mode
    if (isWidget && isChasing) {
      const w = state.size?.width || window.innerWidth || 1920
      const h = state.size?.height || window.innerHeight || 1080

      // Guard: Wait for the canvas to complete its CSS transition to fullscreen
      // before computing screen coordinates (the corner bleed canvas is only ~180px)
      if (w < 500) {
        return
      }

      // Helper: Screen pixel (px, py) -> 3D world coordinate on plane z = 0.3
      const getScreenWorldPoint = (px, py, out) => {
        const ndcX = (px / w) * 2 - 1
        const ndcY = -(py / h) * 2 + 1
        _rayV.set(ndcX, ndcY, 0.5).unproject(state.camera)
        _rayDir.subVectors(_rayV, state.camera.position).normalize()
        const t = (0.3 - state.camera.position.z) / _rayDir.z
        return out.copy(state.camera.position).addScaledVector(_rayDir, t)
      }

      // Target scale for fullscreen running avatar (~165px tall on screen)
      const frustumH = 2 * Math.tan((50 * Math.PI / 360)) * (state.camera.position.z - 0.3)
      const targetChildScale = ((130 / h) * frustumH) / 2.55

      // Corner position where the widget sits
      const originPx = widgetOrigin?.x ?? (w - 84)
      const originPy = widgetOrigin?.y ?? (h - 124)
      getScreenWorldPoint(originPx, originPy, _cornerWorld)

      // On very first frame of chase mode, start smoothly from the corner dock
      if (!wasChasingRef.current) {
        wasChasingRef.current = true
        avatarWorldPos.current.copy(_cornerWorld)
        avatarYaw.current = 0
        avatarPitch.current = 0
        avatarRoll.current = 0
        avatarScale.current = targetChildScale
      }

      // Determine target coordinate in 3D world space
      let targetPx = originPx
      let targetPy = originPy

      if (chasePhase === 'CHASING' && mouseTarget?.current) {
        targetPx = mouseTarget.current.x
        targetPy = mouseTarget.current.y
      } else {
        // RETURNING phase
        targetPx = originPx
        targetPy = originPy
      }

      getScreenWorldPoint(targetPx, targetPy, _targetWorld)

      // Align avatar body/hips with cursor
      const targetX = _targetWorld.x
      const targetY = _targetWorld.y - 0.35

      const dx = targetX - avatarWorldPos.current.x
      const dy = targetY - avatarWorldPos.current.y
      const dist = Math.hypot(dx, dy)

      // If returning and reached corner dock, finish chase mode!
      if (chasePhase === 'RETURNING' && dist < 0.25) {
        onChaseComplete?.()
        return
      }

      // Sprint speed in 3D world units (meters) per second
      // Clamp delta to 0.05 to prevent velocity spikes on frame hitch
      const safeDelta = Math.min(delta, 0.05)
      const speed = chasePhase === 'RETURNING' ? 5.2 : 4.6
      if (dist > 0.04) {
        const moveStep = Math.min(dist, speed * safeDelta)
        avatarWorldPos.current.x += (dx / dist) * moveStep
        avatarWorldPos.current.y += (dy / dist) * moveStep
      }

      // Desktop Goose 360-degree heading orientation:
      if (dist > 0.12) {
        const targetYaw = Math.atan2(dx, -dy)
        let diff = targetYaw - avatarYaw.current
        while (diff < -Math.PI) diff += Math.PI * 2
        while (diff > Math.PI) diff -= Math.PI * 2
        avatarYaw.current += diff * Math.min(1, 14 * safeDelta)

        // Lean into sharp turns (banking roll)
        const targetRoll = THREE.MathUtils.clamp(-diff * 0.35, -0.2, 0.2)
        avatarRoll.current = THREE.MathUtils.damp(avatarRoll.current, targetRoll, 10, safeDelta)

        // Dynamic forward sprint lean
        const targetPitch = THREE.MathUtils.clamp(dist > 0.3 ? 0.15 : 0, 0, 0.2)
        avatarPitch.current = THREE.MathUtils.damp(avatarPitch.current, targetPitch, 8, safeDelta)
      } else {
        // Settled at cursor
        avatarRoll.current = THREE.MathUtils.damp(avatarRoll.current, 0, 8, safeDelta)
        avatarPitch.current = THREE.MathUtils.damp(avatarPitch.current, 0, 8, safeDelta)
      }

      // Smoothly interpolate child scale so avatar stays ~165px tall on fullscreen
      avatarScale.current = THREE.MathUtils.damp(avatarScale.current, targetChildScale, 10, safeDelta)

      // Convert world position to local space of group's parent
      if (group.current && group.current.parent) {
        group.current.parent.updateMatrixWorld(true)
        _targetLocal.copy(avatarWorldPos.current)
        group.current.parent.worldToLocal(_targetLocal)
        group.current.position.set(_targetLocal.x, _targetLocal.y, _targetLocal.z)
        group.current.rotation.set(avatarPitch.current, avatarYaw.current, avatarRoll.current, 'YXZ')
        group.current.scale.set(avatarScale.current, avatarScale.current, avatarScale.current)
      }

      // Update screen pixel position for speech bubble
      if (onScreenPosUpdate) {
        _headPos.copy(avatarWorldPos.current)
        _headPos.y += 0.85 // positioned above running avatar's head
        _headPos.project(state.camera)
        const screenX = (_headPos.x * 0.5 + 0.5) * w
        const screenY = (-_headPos.y * 0.5 + 0.5) * h
        // Clamped to viewport bounds so bubble doesn't get clipped
        const clampedX = Math.max(100, Math.min(w - 100, screenX))
        const clampedY = Math.max(45, Math.min(h - 40, screenY))
        onScreenPosUpdate(clampedX, clampedY)
      }

      return
    }

    // Reset when exiting chase
    if (wasChasingRef.current) {
      wasChasingRef.current = false
      avatarScale.current = 1
      if (group.current) {
        group.current.position.set(0, 0, 0)
        group.current.rotation.set(0, 0, 0)
        group.current.scale.set(1, 1, 1)
      }
    }

    if (!headBone) return

    // Ensure Three.js PropertyMixer never skips updating head and neck bones due to identical consecutive frames
    if (mixer && mixer._bindings) {
      for (let i = 0; i < mixer._bindings.length; i++) {
        const b = mixer._bindings[i]
        if (!b._alwaysApply && (b.binding?.node === headBone || b.binding?.node === neckBone)) {
          const origApply = b.apply
          b.apply = function(accuIndex) {
            origApply.call(this, accuIndex)
            const stride = this.valueSize
            const offset = accuIndex * stride + stride
            this.binding.setValue(this.buffer, offset)
          }
          b._alwaysApply = true
        }
      }
    }

    let targetYaw = 0
    let targetPitch = 0

    if (animationName === "Idle") {
      if (hasCursor.current) {
        headBone.getWorldPosition(_headPos)
        _headPos.project(state.camera)

        // Map canvas NDC to absolute screen pixels
        const rect = state.gl.domElement.getBoundingClientRect()
        const headPixelX = rect.left + (_headPos.x * 0.5 + 0.5) * rect.width
        const headPixelY = rect.top + (-_headPos.y * 0.5 + 0.5) * rect.height

        // Calculate relative cursor position as a fraction of half-window size for full responsiveness
        const halfW = (window.innerWidth || 1920) * 0.5
        const halfH = (window.innerHeight || 1080) * 0.5
        const relX = (globalPointer.current.x - headPixelX) / halfW
        const relY = (globalPointer.current.y - headPixelY) / halfH

        targetYaw = THREE.MathUtils.clamp(relX * MAX_YAW, -MAX_YAW, MAX_YAW) * YAW_DIR
        targetPitch = THREE.MathUtils.clamp(relY * MAX_PITCH, -MAX_PITCH, MAX_PITCH) * PITCH_DIR
      }

      look.current.yaw = THREE.MathUtils.damp(look.current.yaw, targetYaw, LOOK_LAMBDA, delta)
      look.current.pitch = THREE.MathUtils.damp(look.current.pitch, targetPitch, LOOK_LAMBDA, delta)

      // Distribute natural rotation across neck (30%) and head (70%)
      if (neckBone) {
        _euler.set(look.current.pitch * 0.3, look.current.yaw * 0.3, 0, 'YXZ')
        _quat.setFromEuler(_euler)
        neckBone.quaternion.multiply(_quat).normalize()
      }

      _euler.set(look.current.pitch * 0.7, look.current.yaw * 0.7, 0, 'YXZ')
      _quat.setFromEuler(_euler)
      headBone.quaternion.multiply(_quat).normalize()
    } else if (animationName === "Sad Idle" || animationName === "Sad") {
      // Dejected posture: downward tilted head and neck drooping
      const SAD_PITCH = 0.28 // natural downward head tilt (~16°) preserving facial visibility
      look.current.yaw = THREE.MathUtils.damp(look.current.yaw, 0, 5, delta)
      look.current.pitch = THREE.MathUtils.damp(look.current.pitch, SAD_PITCH, 5, delta)

      if (neckBone) {
        _euler.set(look.current.pitch * 0.35, 0, 0, 'YXZ')
        _quat.setFromEuler(_euler)
        neckBone.quaternion.multiply(_quat).normalize()
      }

      _euler.set(look.current.pitch * 0.65, 0, 0, 'YXZ')
      _quat.setFromEuler(_euler)
      headBone.quaternion.multiply(_quat).normalize()
    } else {
      look.current.yaw = 0
      look.current.pitch = 0
    }
  })

  // -- ANIMATION STATE MACHINE -- //
  const [animationName, setAnimationName] = useState(forcedAnimation || "Idle");
  const [interactionPulse, setInteractionPulse] = useState(0);
  const activeActionRef = React.useRef(null);

  // 0. Forced animation override
  useEffect(() => {
    if (forcedAnimation) {
      setAnimationName(forcedAnimation);
    }
  }, [forcedAnimation]);

  useEffect(() => {
    if (typeof window !== 'undefined') {
      if (isWidget) {
        window.__setWidgetAvatarAnimation = setAnimationName;
        window.__widgetAvatar = { mixer, headBone, neckBone, look: look.current, actions };
      } else {
        window.__setAvatarAnimation = setAnimationName;
      }
    }
  }, [isWidget, mixer, headBone, neckBone, actions]);

  // 1. Chase mode priority
  useEffect(() => {
    if (isChasing) {
      setAnimationName("Run");
    } else {
      setAnimationName((prev) => (prev === "Run" ? "Idle" : prev));
    }
  }, [isChasing]);

  // 2. Right-click angry trigger
  useEffect(() => {
    if (!angryPulse || angryPulse <= 0 || isChasing) return;
    setAnimationName("Angry");
    setInteractionPulse((prev) => prev + 1);

    // If Angry is already playing, simply rewind it so it replays immediately without dropping weight
    const angryAction = actions?.[CLIP_FOR_STATE['Angry']] || actions?.['Angry'];
    if (angryAction && activeActionRef.current === angryAction && angryAction.isRunning()) {
      angryAction.time = 0;
      angryAction.paused = false;
      angryAction.play();
    }
  }, [angryPulse, isChasing, actions]);

  // 3. External interaction (hover / click wake)
  useEffect(() => {
    if (!externalInteractionPulse || isChasing) return;
    setAnimationName((prev) => (prev === "Sad Idle" ? "Wave" : prev));
  }, [externalInteractionPulse, isChasing]);

  // 4. Initial widget wave (waves once upon appearing, not after chase ends)
  const hasWavedOnWidgetRef = React.useRef(false);
  useEffect(() => {
    if (isWidget && !hasWavedOnWidgetRef.current) {
      hasWavedOnWidgetRef.current = true;
      setAnimationName("Wave");
    }
  }, [isWidget]);

  useEffect(() => {
    if (isChatOpen) {
      setAnimationName("Wave");
    }
  }, [isChatOpen]);

  // 5. 90-Second Inactivity Timer
  useEffect(() => {
    if (animationName === "Wave" || animationName === "Angry" || animationName === "Run") return;

    let timeout;
    if (animationName === "Idle") {
      timeout = setTimeout(() => {
        setAnimationName("Sad Idle");
      }, 90000);
    }

    return () => clearTimeout(timeout);
  }, [animationName, interactionPulse, externalInteractionPulse]);

  // 6. Seamless Three.js Animation Crossfader (No T-Pose dropout)
  useEffect(() => {
    if (!actions || Object.keys(actions).length === 0) return;

    const clipName = CLIP_FOR_STATE[animationName] || animationName;
    const nextAction = actions[clipName] || actions[animationName];

    if (!nextAction) {
      console.warn(`[Avatar] No clip for "${animationName}". Available: ${Object.keys(actions).join(', ')}`);
      return;
    }

    const prevAction = activeActionRef.current;

    // If next action is already active and running (e.g. re-triggered one-shot), don't crossfade
    if (prevAction === nextAction && nextAction.isRunning()) {
      if (animationName === "Angry" || animationName === "Wave") {
        nextAction.time = 0;
        nextAction.paused = false;
        nextAction.play();
      }
      return;
    }

    // Configure playback mode
    if (animationName === "Angry") {
      nextAction.setLoop(THREE.LoopOnce, 1);
      nextAction.clampWhenFinished = true;
      nextAction.setEffectiveTimeScale(1);
    } else if (animationName === "Wave") {
      nextAction.setLoop(THREE.LoopOnce, 1);
      nextAction.clampWhenFinished = true;
      nextAction.setEffectiveTimeScale(1);
    } else if (animationName === "Run") {
      nextAction.setLoop(THREE.LoopRepeat, Infinity);
      nextAction.clampWhenFinished = false;
      nextAction.setEffectiveTimeScale(1.25);
    } else if (animationName === "Sad Idle") {
      nextAction.setLoop(THREE.LoopRepeat, Infinity);
      nextAction.clampWhenFinished = false;
      nextAction.setEffectiveTimeScale(0.85);
    } else {
      nextAction.setLoop(THREE.LoopRepeat, Infinity);
      nextAction.clampWhenFinished = false;
      nextAction.setEffectiveTimeScale(1);
    }

    nextAction.enabled = true;
    nextAction.setEffectiveWeight(1);

    if (prevAction && prevAction !== nextAction && prevAction.isRunning()) {
      nextAction.time = 0;
      nextAction.paused = false;
      prevAction.crossFadeTo(nextAction, 0.25, false);
      nextAction.play();
    } else {
      nextAction.reset().play();
    }

    activeActionRef.current = nextAction;

    const handleFinished = (e) => {
      if (e.action === nextAction) {
        if (animationName === "Angry" || animationName === "Wave") {
          setAnimationName("Idle");
        }
      }
    };

    mixer.addEventListener('finished', handleFinished);

    return () => {
      mixer.removeEventListener('finished', handleFinished);
      // NOTE: Do NOT call nextAction.fadeOut() here!
      // Three.js's crossFadeTo handles blending out the previous action smoothly
      // when the next action starts, without any dead time or weight loss.
    };
  }, [animationName, actions, mixer]);

  const handleHover = () => {
    setAnimationName((prev) => {
      if (prev === "Sad Idle") {
        return "Wave";
      }
      return prev;
    });
    setInteractionPulse((prev) => prev + 1);
  };

  const handleClick = () => {
    onClick?.();
    handleHover();
  };

  const handleContextMenu = (e) => {
    if (onContextMenu) {
      onContextMenu(e);
    } else {
      if (e?.nativeEvent?.preventDefault) {
        e.nativeEvent.preventDefault();
      } else if (typeof e?.preventDefault === 'function') {
        e.preventDefault();
      }
      setAnimationName((prev) => {
        if (prev === "Sad Idle") return "Wave";
        return prev;
      });
      setInteractionPulse((prev) => prev + 1);
    }
  };

  return (
    <group
      ref={group}
      {...props}
      dispose={null}
    >
      {/* Localized lighting specifically for the Avatar. 
          When in the Hero room and shrunk (isWidget), it turns into a glowing purple portal! */}
      <pointLight
        position={[0, 1.5, 1.5]}
        intensity={isHero && isWidget ? 15 : isChasing ? 0.7 : 3}
        color={isHero && isWidget ? "#a855f7" : "#ffffff"}
        distance={isHero && isWidget ? 3 : 4}
        decay={2}
      />
      <hemisphereLight
        skyColor="#ffffff"
        groundColor="#444444"
        intensity={isHero && isWidget ? 0 : isChasing ? 0.25 : 0.5}
      />

      <group
        name="Scene"
        onPointerOver={!isWidget ? (e) => {
          e.stopPropagation();
          document.body.style.cursor = 'pointer';
          handleHover();
        } : undefined}
        onPointerOut={!isWidget ? () => {
          document.body.style.cursor = 'auto';
        } : undefined}
        onClick={!isWidget ? (e) => {
          e.stopPropagation();
          handleClick();
        } : undefined}
        onContextMenu={!isWidget ? (e) => {
          e.stopPropagation();
          handleContextMenu(e);
        } : undefined}
      >
        <group name="Armature" rotation={[Math.PI / 2, 0, 0]}>
          <primitive object={nodes['mixamorig:Hips'] || nodes.mixamorigHips} />
          <skinnedMesh
            name="Mesh_0"
            geometry={nodes.Mesh_0.geometry}
            material={materials.Avatar_Material}
            skeleton={nodes.Mesh_0.skeleton}
          />
        </group>
      </group>
    </group>
  )
}

